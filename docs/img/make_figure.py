#!/usr/bin/env python3
"""Regenerate docs/img/hero.png: one synthetic page with bleed-through, and what each binariser
makes of it.

    .venv/bin/python docs/img/make_figure.py

The page is synthetic deed-style text (generated by `bench/synth`, no real document content) with a
mirrored second page blended in at strength 0.5, built with the helpers of
`bench/quality_synth_eval.py`. The reference for the F-measure under each panel is the same page
without the second page, thresholded at 128: a stand-in for ground truth, good enough for an
illustration on one page and not a benchmark (the benchmark numbers are in the README). Every panel
is the same crop. Black is what the method calls ink. Pillow's built-in font draws the captions, so
the output does not depend on fonts installed on the machine.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "bench"))
sys.path.insert(0, str(ROOT / "bench" / "synth"))

import metrics  # noqa: E402
import pagetriage_py as pt  # noqa: E402
import quality_synth_eval as q  # noqa: E402
from PIL import Image, ImageDraw, ImageFont  # noqa: E402

OUT = Path(__file__).resolve().parent / "hero.png"

W, H, DPI = 827, 1170, 150          # A5 at 150 dpi
q.W, q.H = W, H
# Pillow's built-in font has no en dash (it would print as an empty box); swap it for a colon. The
# random draws, and so the layout, are unchanged.
_paragraph = q.synthtext.paragraph
q.synthtext.paragraph = lambda *a, **k: _paragraph(*a, **k).replace("–", ":")

BLEED_STRENGTH = 0.5
CROP = (60, 372, 560, 672)          # left, top, right, bottom in page pixels: lines with show-through
SCALE = 0.8
PANEL_W, PANEL_H = round((CROP[2] - CROP[0]) * SCALE), round((CROP[3] - CROP[1]) * SCALE)
GAP, PAD, CAPTION_H = 14, 18, 46
PAPER, INK, FG, MUTED, BG, EDGE = 253, 25, (23, 25, 35), (84, 92, 108), (232, 235, 241), (190, 196, 208)

METHODS = [
    ("Otsu", "one threshold for the whole page", "otsu", None),
    ("Sauvola", "threshold from the local neighbourhood", "sauvola", None),
    ("Wolf-Jolion", "local, adjusts for contrast", "wolf", None),
    ("Howe, static", "graph cut over edges", "howe", '[howe]\nmode = "static"'),
]


def ink_mask(img: Image.Image, method: str, params: str | None) -> np.ndarray:
    ink = pt.binarize(img.tobytes(), img.width, img.height, method, params)
    return np.frombuffer(ink, np.uint8).reshape(img.height, img.width).astype(bool)


def mask_to_image(mask: np.ndarray) -> Image.Image:
    return Image.fromarray(np.where(mask, INK, PAPER).astype(np.uint8), "L")


def main() -> None:
    front = q.render("latin", seed=11)
    back = q.render("latin", seed=12)
    page = q.composite_bleed(front, back, BLEED_STRENGTH)
    reference = np.asarray(front) < 128

    quality = json.loads(pt.analyse_page(page.tobytes(), W, H, DPI))["quality"]
    panels = [("Page with bleed-through", "what the scanner saw", page)]
    for name, blurb, method, params in METHODS:
        mask = ink_mask(page, method, params)
        f = metrics.f_measure(mask, reference)
        panels.append((f"{name}   F {f:.1f}", blurb, mask_to_image(mask)))

    font = ImageFont.load_default(size=15)
    small = ImageFont.load_default(size=12)
    cols, rows = 3, 2
    width = PAD * 2 + cols * PANEL_W + (cols - 1) * GAP
    height = PAD * 2 + rows * (PANEL_H + CAPTION_H) + (rows - 1) * GAP
    sheet = Image.new("RGB", (width, height), BG)
    draw = ImageDraw.Draw(sheet)
    for i, (title, blurb, img) in enumerate(panels):
        c, r = i % cols, i // cols
        x = PAD + c * (PANEL_W + GAP)
        y = PAD + r * (PANEL_H + CAPTION_H + GAP)
        crop = img.crop(CROP).resize((PANEL_W, PANEL_H), Image.LANCZOS)
        sheet.paste(crop.convert("RGB"), (x, y))
        draw.rectangle((x - 1, y - 1, x + PANEL_W, y + PANEL_H), outline=EDGE)
        draw.text((x, y + PANEL_H + 8), title, fill=FG, font=font)
        draw.text((x, y + PANEL_H + 28), blurb, fill=MUTED, font=small)

    # sixth cell: what the figure is, and pagetriage's own readout for this page
    x = PAD + 2 * (PANEL_W + GAP)
    y = PAD + (PANEL_H + CAPTION_H + GAP)
    lines = [
        ("Same page, same crop, five views.", True),
        ("", False),
        ("F: agreement with the ink of the clean page", False),
        ("(DIBCO F-measure). One synthetic page: an", False),
        ("illustration, not a benchmark.", False),
        ("", False),
        ("pagetriage's readout for this page:", False),
        (f"  bleed-through {quality['bleed_through']:.2f}, grade {quality['grade']}", False),
        (f"  recommended binariser: {quality['recommended_binarizer'].capitalize()}", False),
    ]
    for k, (text, bold) in enumerate(lines):
        draw.text((x, y + 8 + k * 19), text, fill=FG if bold or k >= 6 else MUTED, font=font if bold else small)
    # Few distinct tones (paper, ink, a gray page and captions): a small palette keeps the file small.
    sheet = sheet.quantize(colors=48, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    sheet.save(OUT, optimize=True)
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB, {width}x{height})")
    for title, _, _ in panels:
        print(" ", title)
    print("  readout:", quality["bleed_through"], quality["grade"], quality["recommended_binarizer"])


if __name__ == "__main__":
    main()
