#!/usr/bin/env python3
"""Write crates/pagetriage-core/src/pixel/qr_tables.rs: the block structure and alignment-pattern
positions of ISO/IEC 18004 QR versions 1-40, read from the `qrcode` Python package (a development-time
tool; the core does not depend on it).

    pip install qrcode && python3 scripts/gen_qr_tables.py

The output is committed. The table of error-correction blocks per version and level is a fact of the
standard; this script is how the committed values were produced, and `tests/golden/qr_vectors.json`
(made by tests/golden/gen_qr_vectors.py with the same package) checks them end to end by decoding real
codes of many versions.
"""
import pathlib

import qrcode.base as base
import qrcode.util as util

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/pagetriage-core/src/pixel/qr_tables.rs"


def main():
    rows = base.RS_BLOCK_TABLE
    assert len(rows) == 160
    lines = [
        "//! QR code block structure and alignment-pattern positions (ISO/IEC 18004), versions 1 to 40.",
        "//! Generated by scripts/gen_qr_tables.py; do not edit by hand.",
        "",
        "/// Per version (1 to 40) and error-correction level (L, M, Q, H): `[blocks of group 1, codewords",
        "/// per block, data codewords per block, blocks of group 2, codewords per block, data codewords",
        "/// per block]`; group 2 is all zeros when absent.",
        "pub const BLOCKS: [[[u16; 6]; 4]; 40] = [",
    ]
    for v in range(40):
        lines.append("    [")
        for level in range(4):
            r = list(rows[v * 4 + level])
            r += [0] * (6 - len(r))
            lines.append("        [" + ", ".join(str(x) for x in r) + "],")
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    lines.append("/// Centres of the alignment patterns along each axis, per version (1 to 40).")
    lines.append("pub const ALIGNMENT: [&[u8]; 40] = [")
    for v in range(40):
        lines.append("    &[" + ", ".join(str(x) for x in util.PATTERN_POSITION_TABLE[v]) + "],")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
